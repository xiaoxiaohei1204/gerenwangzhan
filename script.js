const tabs = document.querySelectorAll(".tab");
const panels = document.querySelectorAll(".panel");
const langToggle = document.querySelector(".lang-toggle");
let currentLang = localStorage.getItem("portfolioLanguage") || "zh";

function setActiveTab(tabName) {
  tabs.forEach((tab) => tab.classList.toggle("is-active", tab.dataset.tab === tabName));
  panels.forEach((panel) => panel.classList.toggle("is-active", panel.dataset.panel === tabName));
  history.replaceState(null, "", `#${tabName}`);
}

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = lang === "zh" ? "李顺章 | 个人作品网站" : "Li Shunzhang | Portfolio";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = translations[lang][key] || element.textContent;
  });
  document.querySelectorAll(".work-card").forEach((card) => {
    const button = card.querySelector(".detail-toggle");
    button.textContent = translations[lang][card.classList.contains("is-open") ? "works.collapse" : "works.expand"];
  });
  langToggle.querySelector("b").textContent = lang === "zh" ? "EN" : "中文";
  localStorage.setItem("portfolioLanguage", lang);
}

tabs.forEach((tab) => {
  tab.addEventListener("click", () => setActiveTab(tab.dataset.tab));
});

document.querySelectorAll("[data-jump]").forEach((button) => {
  button.addEventListener("click", () => setActiveTab(button.dataset.jump));
});

langToggle.addEventListener("click", () => {
  applyLanguage(currentLang === "zh" ? "en" : "zh");
});

document.querySelectorAll(".detail-toggle").forEach((button) => {
  button.addEventListener("click", () => {
    const card = button.closest(".work-card");
    card.classList.toggle("is-open");
    button.textContent = translations[currentLang][card.classList.contains("is-open") ? "works.collapse" : "works.expand"];
  });
});

document.querySelectorAll(".work-controls a[href='#']").forEach((link) => {
  link.addEventListener("click", (event) => event.preventDefault());
});

const initialTab = location.hash.replace("#", "");
if (["home", "about", "works", "contact"].includes(initialTab)) {
  setActiveTab(initialTab);
}

applyLanguage(currentLang);
